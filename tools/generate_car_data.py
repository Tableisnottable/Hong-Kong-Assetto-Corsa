"""Generate Assetto Corsa car physics data (*.ini) for all 6 HK exam vehicles.

Reads specs from car/driving test car/ and writes complete data/*.ini files
into content/cars/<car_id>/data/ for each vehicle.

Usage:
    python tools/generate_car_data.py

All values derived from the real vehicle spec sheets in car/driving test car/.
Units: AC uses metric (kg, meters, kW, Nm, rpm).
"""

from __future__ import annotations

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CARS_DIR = os.path.join(ROOT, "content", "cars")


def power_kw(hp: float) -> float:
    return round(hp * 0.7355, 1)


def write(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def engine_curve(power_hp: float, torque_nm: float, rpm_power: int,
                 rpm_torque: int, rpm_idle: int, rpm_limit: int,
                 steps: int = 9) -> str:
    """Build a simple parabolic-ish power.lut table peaking at rpm_power."""
    lines = []
    for i in range(steps + 1):
        rpm = int(rpm_idle + (rpm_limit - rpm_idle) * i / steps)
        # torque factor: rises to 1.0 at rpm_torque, holds, falls after rpm_power
        if rpm <= rpm_torque:
            f = 0.55 + 0.45 * (rpm - rpm_idle) / max(1, (rpm_torque - rpm_idle))
        elif rpm <= rpm_power:
            f = 1.0
        else:
            f = max(0.55, 1.0 - 0.45 * (rpm - rpm_power) / max(1, (rpm_limit - rpm_power)))
        tq = round(torque_nm * f)
        lines.append(f"{rpm}|{tq}")
    return "\n".join(lines)


def make_car_ini(mass_kg: int, wheelbase_m: float, track_f_m: float,
                 track_r_m: float, length_m: float, width_m: float,
                 height_m: float, fuel_l: int, steer_lock_deg: int,
                 drivetrain: str = "RWD") -> str:
    return f"""; Generated by tools/generate_car_data.py - DO NOT EDIT MANUALLY
[BASIC]
MASS={mass_kg}
; dimensions in meters
WHEELBASE={wheelbase_m:.3f}
TRACK_FRONT={track_f_m:.3f}
TRACK_REAR={track_r_m:.3f}
LENGTH={length_m:.3f}
WIDTH={width_m:.3f}
HEIGHT={height_m:.3f}
FUEL_TANK_LITERS={fuel_l}

[CONTROLS]
STEER_LOCK={steer_lock_deg}
DRIVETRAIN={drivetrain}
"""


def make_engine_ini(power_hp: float, torque_nm: float, rpm_power: int,
                    rpm_torque: int, rpm_idle: int, rpm_limit: int,
                    fuel_type: str = "petrol") -> str:
    curve = engine_curve(power_hp, torque_nm, rpm_power, rpm_torque,
                         rpm_idle, rpm_limit)
    return f"""; Generated by tools/generate_car_data.py - DO NOT EDIT MANUALLY
[ENGINE]
POWER_HP={power_hp}
TORQUE_NM={torque_nm}
RPM_POWER={rpm_power}
RPM_TORQUE={rpm_torque}
IDLE_RPM={rpm_idle}
LIMITER_RPM={rpm_limit}
FUEL_TYPE={fuel_type}

[POWER_CURVE]
; rpm|torque_nm
{curve}
"""


def make_drivetrain_ini(gears: list[float], final: float, reverse: float,
                        auto: bool = False) -> str:
    lines = [f"; Generated by tools/generate_car_data.py - DO NOT EDIT MANUALLY",
             "[GEARS]"]
    for i, r in enumerate(gears, start=1):
        lines.append(f"GEAR_{i}={r:.3f}")
    lines.append(f"REVERSE={reverse:.3f}")
    lines.append(f"FINAL={final:.3f}")
    lines.append("")
    lines.append("[TRANSMISSION]")
    lines.append(f"AUTOMATIC={'1' if auto else '0'}")
    return "\n".join(lines) + "\n"


def make_suspension_ini(track_f_m: float, track_r_m: float,
                        wheelbase_m: float, mass_kg: int,
                        front_type: str = "MacPherson",
                        rear_type: str = "TorsionBeam") -> str:
    # spring rates scaled roughly with corner mass (N/m)
    corner = mass_kg * 9.81 / 4
    spring_f = int(corner * 2.2)
    spring_r = int(corner * 2.0)
    return f"""; Generated by tools/generate_car_data.py - DO NOT EDIT MANUALLY
[FRONT]
TYPE={front_type}
TRACK={track_f_m:.3f}
SPRING_RATE={spring_f}
DAMPER_BUMP=2500
DAMPER_REBOUND=3500
CAMBER=-0.5
TOE=0.05

[REAR]
TYPE={rear_type}
TRACK={track_r_m:.3f}
SPRING_RATE={spring_r}
DAMPER_BUMP=2500
DAMPER_REBOUND=3500
CAMBER=-0.5
TOE=0.05

[GEOMETRY]
WHEELBASE={wheelbase_m:.3f}
CG_HEIGHT=0.55
"""


def make_tyres_ini(width_mm: int, aspect: int, rim_in: int,
                   pressure_f: float = 2.3, pressure_r: float = 2.2) -> str:
    # overall diameter in meters
    sidewall = width_mm * aspect / 100 / 1000
    diameter = rim_in * 0.0254 + 2 * sidewall
    return f"""; Generated by tools/generate_car_data.py - DO NOT EDIT MANUALLY
[FRONT]
WIDTH_MM={width_mm}
ASPECT={aspect}
RIM_IN={rim_in}
DIAMETER_M={diameter:.3f}
PRESSURE_BAR={pressure_f:.1f}

[REAR]
WIDTH_MM={width_mm}
ASPECT={aspect}
RIM_IN={rim_in}
DIAMETER_M={diameter:.3f}
PRESSURE_BAR={pressure_r:.1f}

[GRIP]
DRY=1.00
WET=0.85
"""


def make_brakes_ini(front_mm: int, rear_mm: int, rear_drum: bool = False,
                    bias_front: float = 0.65, abs_on: bool = True) -> str:
    rear_type = "DRUM" if rear_drum else "DISC"
    return f"""; Generated by tools/generate_car_data.py - DO NOT EDIT MANUALLY
[FRONT]
DISC_MM={front_mm}
TYPE=VENTED_DISC

[REAR]
DISC_MM={rear_mm}
TYPE={rear_type}

[BIAS]
FRONT={bias_front:.2f}

[ABS]
ENABLED={'1' if abs_on else '0'}
"""


def make_ui_json(name: str, brand: str, description: str, tags: list[str],
                 specs: dict) -> str:
    import json
    payload = {
        "name": name,
        "brand": brand,
        "description": description,
        "tags": tags,
        "class": "street",
        "specs": specs,
    }
    return json.dumps(payload, ensure_ascii=False, indent=4)


