def main() -> None:
    count = 0
    for car_id, v in VEHICLES.items():
        data_dir = os.path.join(CARS_DIR, car_id, "data")
        ui_dir = os.path.join(CARS_DIR, car_id, "ui")

        write(os.path.join(data_dir, "car.ini"),
              make_car_ini(v["mass"], v["wheelbase"], v["track_f"],
                           v["track_r"], v["length"], v["width"],
                           v["height"], v["fuel"], v["steer_lock"],
                           v["drivetrain"]))
        write(os.path.join(data_dir, "engine.ini"),
              make_engine_ini(v["power_hp"], v["torque_nm"], v["rpm_power"],
                              v["rpm_torque"], v["rpm_idle"], v["rpm_limit"],
                              v.get("fuel_type", "petrol")))
        write(os.path.join(data_dir, "drivetrain.ini"),
              make_drivetrain_ini(v["gears"], v["final"], v["reverse"],
                                  v["auto"]))
        write(os.path.join(data_dir, "suspension.ini"),
              make_suspension_ini(v["track_f"], v["track_r"],
                                  v["wheelbase"], v["mass"],
                                  v["front_susp"], v["rear_susp"]))
        write(os.path.join(data_dir, "tyres.ini"),
              make_tyres_ini(v["tyre_w"], v["tyre_a"], v["rim"]))
        write(os.path.join(data_dir, "brakes.ini"),
              make_brakes_ini(v["brake_f"], v["brake_r"], v["rear_drum"]))
        write(os.path.join(ui_dir, "ui_car.json"),
              make_ui_json(v["name"], v["brand"], v["description"],
                           v["tags"], v["specs"]))
        count += 1
        print(f"  [OK] {car_id}: {v['name']} ({v['power_hp']}hp, {v['mass']}kg)")
    print(f"[DONE] Generated data for {count} vehicles.")


if __name__ == "__main__":
    main()
