"""Make visual bus axles update for their own native AI car, outside the cockpit."""
import argparse
import datetime
import hashlib
import json
from pathlib import Path
import re
import subprocess

import numpy as np
from kn5_tools import Kn5
from prepare_kmb_ai_grid import ROOT, buses, write_backed_up
from repair_omsi_bus_physics import AC, world_vertices


def configure_car(car, backup):
    model = Kn5(car / (car.name + ".kn5"))
    tags = [n for n in model.root.children if n.name in
            ("E6M_TAG_LR", "E6M_TAG_RR", "OMSI_TAG_TAG_L", "OMSI_TAG_TAG_R")]
    if not tags:
        return None
    bindings = []
    for n in tags:
        points = np.concatenate(list(world_vertices(n)))
        radius = float(np.linalg.norm(points[:, 1:3] - n.matrix[3, 1:3], axis=1).max())
        if not .3 < radius < .7:
            raise ValueError("Unexpected visual axle radius: " + n.name)
        bindings.append((n.name, radius))
    lua = (
        "-- Associated car is supplied by CSP; never substitute the player car.\n"
        "local root = ac.findNodes('carRoot:' .. car.index)\n"
        "local wheels = {\n" + "".join(f"  {{node = root:findNodes('{name}'), radius = {radius:.8f}, angle = 0}},\n" for name, radius in bindings) +
        "}\nfunction script.update(dt)\n"
        "  local distance = car.localVelocity.z * dt\n"
        "  for _, wheel in ipairs(wheels) do\n"
        "    wheel.node:rotate(vec3(1, 0, 0), distance / wheel.radius)\n"
        "  end\nend\n")
    ext = car / "extension"
    config = ext / "ext_config.ini"
    text = config.read_text(encoding="utf-8-sig") if config.exists() else ""
    # Remove only the obsolete inline block generated by our family converter.
    text = re.sub(r'(?ms)^\[SCRIPT_\.\.\.\]\s*\nSCRIPT="\s*\nlocal car = ac\.getCar\(\).*?OMSI_TAG_TAG_L.*?^"\s*\n?', '', text)
    text = re.sub(r'(?ms)^\[SCRIPT_KMB_AI_AXLES\]\s*\n.*?(?=^\[|\Z)', '', text)
    text = re.sub(r'(?ms)^\[SCRIPT_KMB_PLAYER_AXLES\]\s*\n.*?(?=^\[|\Z)', '', text)
    text = re.sub(r'(?ms)^; KMB_EXTRA_AXLE_SCRIPT\s*\n\[SCRIPT_\.\.\.\]\s*\n.*?(?=^\[|\Z)', '', text)
    text = text.rstrip() + (
        "\n\n; KMB_EXTRA_AXLE_SCRIPT\n[SCRIPT_...]\nSCRIPT=kmb_ai_axles.lua\n"
        "ACTIVE_FOR_UNFOCUSED=1\nACTIVE_FOR_NEAREST=64\n")
    write_backed_up(config, text.encode("utf-8"), backup)
    write_backed_up(ext / "kmb_ai_axles.lua", lua.encode("utf-8"), backup)
    cockpit = ext / "cockpit.lua"
    if cockpit.exists():
        source = cockpit.read_text(encoding="utf-8-sig")
        # Give the independent script sole ownership of E6M tag rotations.
        updated = re.sub(r"(?m)^  if bindings\.car == 'E6M' then\n    tagAngle = .*?\n    tagL:setRotation.*?\n    tagR:setRotation.*?\n  end\n", "", source)
        if updated != source:
            write_backed_up(cockpit, updated.encode("utf-8"), backup)
    return {"car": car.name, "wheels": [{"node": n, "radius": r} for n, r in bindings],
            "script_sha256": hashlib.sha256(lua.encode("utf-8")).hexdigest(), "backup": str(backup)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ac", type=Path, default=AC)
    parser.add_argument("--output", type=Path, default=ROOT / "outputs/KMB_AI")
    parser.add_argument("--packages", type=Path, help="Also update matching local converted packages")
    args = parser.parse_args()
    procs = subprocess.run(["tasklist", "/FI", "IMAGENAME eq acs.exe", "/FO", "CSV"], capture_output=True, text=True, check=True)
    if '"acs.exe"' in procs.stdout.lower():
        raise RuntimeError("Close AC before installing native wheel scripts")
    backup = args.output / "backups" / datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    checks = []
    fleet = []
    from luaparser import ast
    for bus in buses():
        car = args.ac / "content/cars" / bus["id"]
        result = configure_car(car, backup / bus["id"])
        if result:
            ast.parse((car / "extension/kmb_ai_axles.lua").read_text(encoding="utf-8"))
            ast.parse((car / "extension/cockpit.lua").read_text(encoding="utf-8")) if (car / "extension/cockpit.lua").exists() else None
            if args.packages:
                for package_car in args.packages.glob("*/content/cars/" + bus["id"]):
                    configure_car(package_car, backup / (bus["id"] + "_package"))
            checks.append(result)
            fleet.append({"car": bus["id"], "visual_axles": result["wheels"], "status": "ANIMATED"})
        else:
            fleet.append({"car": bus["id"], "visual_axles": [],
                          "status": "TWO_AXLE_MODEL_NO_EXTRA_AXLE_NODES"})
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "native_axle_animation.json").write_text(json.dumps(
        {"status": "PASS", "fleet": fleet, "cars": checks, "lua_syntax": "PASS",
         "runtime": "pending user AI wheel test"}, indent=2), encoding="utf-8")
    print(json.dumps(checks, indent=2))


if __name__ == "__main__":
    main()
